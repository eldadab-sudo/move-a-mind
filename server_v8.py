    def do_GET(self):
        p = urlparse(self.path).path
        if p == '/':
            f = app.WEB / 'index.html'
            html = f.read_text(encoding='utf-8')
            old = 'const tracks=[["sales","מכירות / שירות","לקוח סקפטי שצריך להתקדם בלי לחץ"],["work","ניהול / עבודה","עמית/ה שמתנגד/ת לשינוי"],["parent","הורות","שיחה על אחריות וגבולות"],["teacher","הוראה / חינוך","שיחה עם הורה מודאג"],["everyday","חיי יום-יום","מחלוקת רגילה בין אנשים"]];'
