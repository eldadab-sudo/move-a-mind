app = v12.app

# Explicit participant roles for every simulation.
ROLE_MAP = {
    'sales': ('איש/ת המכירות או השירות', 'הלקוח/ה'),
    'work': ('המנהל/ת', 'העובד/ת'),
    'military': ('המפקד/ת', 'החייל/ת'),
    'restaurant': ('עובד/ת המסעדה', 'הלקוח/ה'),
    'parent': ('ההורה', 'הילד/ה'),
    'teacher': ('המורה/מחנכ/ת', 'ההורה'),
    'everyday': ('האדם שמנסה לקדם את ההצעה', 'החבר/ה שמתנגד/ת'),
}

# Clarify briefs so the tester always knows who they are.
app.SCENARIOS['sales']['brief'] = 'את/ה איש/ת המכירות או השירות. מולך נועם, לקוח/ה סקפטי/ת שמנהל/ת עסק קטן. כבר הייתה לו/ה חוויה לא טובה ממערכת דומה והוא/היא לא רוצה שוב לבזבז זמן וכסף. נועם פותח/ת בהתנגדות. התפקיד שלך הוא להבין מה מפריע לו/ה, להתמודד עם ההתנגדויות, לבנות אמון ולנסות להגיע לצעד אמיתי כמו דמו, פיילוט, דחייה או ויתור על העסקה.'
app.SCENARIOS['work']['brief'] = 'את/ה המנהל/ת. אורי, עובד ותיק ומוערך, מבקש יום חופש מלא ביום חמישי הקרוב. בגלל מעבר מערכת קריטי ושני עובדים שכבר בחופש, אינך יכול/ה כרגע לאשר לו יום מלא. אורי פותח את השיחה. התפקיד שלך הוא לנהל את ההתנגדות, להבין למה היום חשוב לו, להסביר את המגבלה ולנסות להגיע לפתרון אמיתי או לאי-הסכמה מכבדת.'
app.SCENARIOS['military']['brief'] = 'את/ה המפקד/ת. עידו, חייל מקצועי ומוערך בצוות, רוצה לעבור ליחידה אחרת. את/ה מעוניין/ת שישאר משום שהוא משמעותי לצוות ולמשימה. עידו פותח את השיחה ומסביר שהוא רוצה לעבור. התפקיד שלך הוא להבין מה מניע אותו, להתמודד עם ההתנגדויות שלו להישאר, לבדוק אם אפשר להציע שינוי אמיתי, ולהגיע להחלטה מכבדת — הישארות, תקופת ניסיון בתנאים ברורים או תמיכה במעבר.'
app.SCENARIOS['restaurant']['brief'] = 'את/ה עובד/ת המסעדה. מיכל, לקוחה לא מרוצה, מבקשת לדבר איתך אחרי שהמנה שלה הגיעה באיחור ופושרת והיא הרגישה שמתעלמים ממנה. מיכל פותחת את השיחה. התפקיד שלך הוא להבין מה באמת מפריע לה עכשיו, לטפל בהתנגדות ובכעס, לקחת אחריות במקום המתאים ולהוביל לפתרון סביר במסגרת הסמכות שלך.'
app.SCENARIOS['parent']['brief'] = 'את/ה ההורה. תום, בן/בת 15, רוצה לחזור מאירוע חברתי בשבת ב-01:30. את/ה לא מוכן/ה כרגע לשעה כזו בגלל נסיעה מאוחרת והסעה לא ברורה. תום פותח את השיחה. התפקיד שלך הוא להתמודד עם ההתנגדות שלו/ה, להציב גבול, להבין מה חשוב לו/ה ולנסות להגיע להסכמה בטוחה ומכבדת.'
app.SCENARIOS['teacher']['brief'] = 'את/ה המורה/מחנכ/ת. רוני, הורה לתלמיד/ה שלך, מתנגד/ת להשתתפות של הילד/ה בקבוצת תגבור קטנה במתמטיקה. רוני פותח/ת את השיחה. התפקיד שלך הוא להתמודד עם ההתנגדויות, להבין מה באמת מטריד את ההורה, להסביר את ההמלצה ולנסות להגיע להסכמה מעשית או לאי-הסכמה מכבדת.'
app.SCENARIOS['everyday']['brief'] = 'את/ה האדם שמנסה לקדם שינוי בתוכנית. קבוצת חברים כבר סגרה מסלול טיול בכרמל, ואת/ה רוצה לעבור למסלול חדש בגליל. יעל, שמרכזת את הקבוצה, מתנגדת לשינוי ופותחת את השיחה. התפקיד שלך הוא להבין את ההתנגדות שלה, להתמודד עם החששות ולנסות להגיע להסכמה, תנאי לבדיקה או החלטה להישאר עם התוכנית המקורית.'

_previous = app.scenario_system
def scenario_system(sc, turn):
    base = _previous(sc, turn)
    track = None
    for k,v in app.SCENARIOS.items():
        if v is sc:
            track = k
            break
    if track in ROLE_MAP:
        user_role, ai_role = ROLE_MAP[track]
        role_rule = f'''\nחלוקת תפקידים מחייבת לאורך כל השיחה:\n- המשתמש הוא {user_role}.\n- אתה הוא {ai_role}.\nאסור להחליף תפקידים, לדבר בשם המשתמש, לנסח עבורו תשובה, או להפוך אותו לצד שמתנגד לעצמו. אתה תמיד מגלם רק את הצד שמול המשתמש.'''
        if turn == 0:
            role_rule += '\nחובה: אתה, הצד שמול המשתמש, פותח את השיחה ראשון בצורה טבעית ובגוף ראשון.'
        return base + role_rule
    return base
app.scenario_system = scenario_system

if __name__ == '__main__':
    os.chdir(app.ROOT)
    print('Move A Mind v1.7 participant-role consistency')
    ThreadingHTTPServer(('0.0.0.0', app.PORT), v12.v11.v10.H).serve_forever()
