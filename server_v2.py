def demo_reply(track,text):
    t=text.lower()
    asks='?' in text or any(x in t for x in ['מה מפריע','מה מדאיג','מה חשוב','למה','מה החשש'])
    small=any(x in t for x in ['ניסיון','פיילוט','שבוע','צעד קטן','נבדוק','חלופה','לבחור','בחירה','תוכנית גיבוי'])
    if track=='sales':
        if asks:return random.choice(['הזמן. מי ילמד את הצוות ומה קורה אם אחרי שבוע כולם חוזרים ל-WhatsApp?','אני צריך להבין כמה עבודה זה דורש ממני בשבוע הראשון, לא רק מה זה חוסך אחר כך.'])
        if small:return 'אם זה ניסיון קצר בלי להעביר את כל העסק ביום אחד, אני מוכן לשמוע. מה בדיוק בודקים בניסיון?'
        return random.choice(['מה אתה מבקש ממני לעשות ביום הראשון?','איך אתה מונע מצב שאני משלם ובסוף אף אחד לא משתמש?'])
    if track=='work':
        if asks:return 'אני חוששת שהרעיון יהפוך לעוד משימה שאני אצטרך להזכיר לכולם. מי מחזיק את זה יחד איתי?'
        if small:return 'ניסוי מוגבל נשמע סביר. מה נחשב הצלחה ומי עוד אחראי חוץ ממני?'
        return random.choice(['כבר ניסינו תהליכים שנעלמו אחרי שבוע. למה שהפעם זה יחזיק?','אני לא נגד הרעיון; אני נגד זה שכל הביצוע ייפול עליי.'])
    if track=='parent':
        if asks:return 'הבעיה שלי היא שלא שאלו אותי. יש ימים שאני חוזר מאוחר, ואם הייתה לי בחירה אולי הייתי מסכים.'
        if small:return 'אם אני יכול לבחור את הימים או לבחור בין שתי מטלות, זה כבר מרגיש הוגן יותר.'
        return random.choice(['אני לא אומר שאני לא אעשה כלום. אני רוצה להיות חלק מההחלטה.','ומה קורה בשבוע שיש לי מבחן או משהו חריג?'])
    if track=='teacher':
        if asks:return 'אני רוצה לדעת איך תמדדו התקדמות, מתי תעדכנו אותי ומה תעשו אם רואים קושי.'
        if small:return 'אם יש בדיקת אמצע וקריטריונים ברורים, אני מוכן לתת לזה הזדמנות.'
        return random.choice(['איזה נתון בפועל יראה לכם שהשיטה עובדת?','אני צריך משהו יותר קונקרטי מ"נראה איך זה הולך".'])
    if track=='everyday':
        if asks:return 'בעיקר האחריות. אם אין חניה או חוזרים מאוחר, כולם באים אליי כי אני ארגנתי.'
        if small:return 'אם אתה לוקח על עצמך לבדוק חניה וזמנים ויש מסלול גיבוי, אני מוכנה לשקול את החדש.'
        return random.choice(['מי בודק שהמסלול מתאים לכל הקבוצה?','אני מוכנה לשינוי, אבל לא רוצה להיות היחידה שאחראית לפרטים.'])
server.demo_reply=demo_reply

