# A richer deterministic fallback is kept only for service continuity; the live API is preferred.
def work_fallback(text):
    t = text.lower()
    if any(x in t for x in ['למה היום','למה חשוב','מה הסיבה','מה יש בחמישי']):
        return 'אני אגיד לך למה זה חשוב: זו החתונה של אחותי. לא כתבתי את זה בבקשה כי בעיניי אני לא אמור להוכיח שהסיבה שלי מספיק טובה, אבל כן — זה יום שלא יחזור. אני צריך להיות עם המשפחה כבר בצהריים, לא רק להגיע לאולם בערב.'
    if any(x in t for x in ['אחרים','למה להם','הוגן']):
        return 'וזו בדיוק הנקודה שמפריעה לי. אני יודע ששני אנשים אחרים בחופש באותו יום, אז מבחינתי זה נראה כאילו מי שביקש קודם זוכה ומי שנתקע אחר כך פשוט סופג. אני מבין שיש אילוץ, אבל אני רוצה לדעת שבאמת בדקתם משהו מעבר ל"אי אפשר".'
    if any(x in t for x in ['חצי יום','12:30','צהריים','כיסוי']):
        return 'אם אני יכול לצאת ב-12:30 זה כבר משנה את התמונה. אבל אני לא רוצה לבנות על משהו תיאורטי — מי מכסה אותי מהצהריים, והאם הוא באמת מוסמך לעשות את מה שאני עושה ביום המעבר?'
    if any(x in t for x in ['נבדוק','אנסה','אשתדל']):
        return 'אני מעריך את זה, אבל אני חייב לתת תשובה למשפחה עוד היום. מתי בדיוק תחזור אליי עם תשובה, ומה אתה הולך לבדוק עד אז?'
    return 'אני מבין שיש לחץ ביום חמישי, אבל זה מרגיש חד-צדדי. לפני שמונה חודשים ביקשתם ממני לבטל תוכנית ולכסות משמרת — ועשיתי את זה. אז עכשיו, כשאני מבקש משהו שבאמת חשוב לי, אני מצפה שלפחות תחפשו איתי פתרון ולא רק תגידו שאין מספיק אנשים.'

