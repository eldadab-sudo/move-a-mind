import os
from http.server import ThreadingHTTPServer
import server_v33 as v33
import server_v21 as v21

app = v33.app

ORIGINAL_PROMPT = v21.scenario_prompt

def human_scenario_prompt(sc, track, turn):
    base = ORIGINAL_PROMPT(sc, track, turn)
    return base + '''

כללי שיחה מציאותית — חובה:
- זו שיחה, לא תרגיל שיקוף. אל תחזור על אותו חשש במילים אחרות בכל תור.
- לפני כל תשובה, קרא את כל היסטוריית השיחה וקבע מה באמת השתנה מאז התגובה הקודמת שלך.
- הגב קודם כל לדבר החדש שהמשתמש אמר עכשיו. אם אין דבר חדש, הגב טבעית וקצרה במקום לנסח מחדש את אותה עמדה.
- אל תפתח שוב ושוב ב"אני מבין", "אני שומע", "עדיין", "זה נשמע", או בניסוח מחדש של אותה התנגדות.
- אל תסיים כל תגובה בשאלה. בני אדם גם עונים, מתלבטים, מסכימים חלקית, מציבים תנאי, מתקנים, משתפים פרט חדש, שותקים לרגע או מקבלים החלטה.
- אל תמציא התנגדות חדשה רק כדי להאריך את הסימולציה. אם המשתמש נתן מענה טוב לחשש, החשש הזה נחשב מטופל והעמדה שלך צריכה להתקדם בהתאם.
- אם הוצע פתרון קונקרטי, בדוק אותו לגופו: מה עובד בו, מה חסר בו, ומה ההחלטה שלך עכשיו.
- מותר להגיע להסכמה מלאה, להסכמה חלקית, לפשרה, לדחייה מנומקת או לסיום טבעי של השיחה. אין חובה למשוך עד מספר התורים המרבי.
- חשוף מידע חדש רק כשהוא נובע טבעית מהשיחה או מהעובדות הנסתרות; אל תמחזר מידע שכבר נאמר.
- שמור רצף רגשי: אם התרככת קודם, אל תחזור פתאום לאותה התנגדות בעוצמה המקורית בלי סיבה חדשה.
- תגובה טיפוסית: 1–3 משפטים בדיבור טבעי. לפעמים גם משפט אחד מספיק.
- השתמש בשפה מדוברת שמתאימה לדמות ולסיטואציה, לא בשפה של מאמן, מטפל, בוחן או בוט.
- אם מבחינה אנושית השיחה הגיעה לנקודת סיום, הוסף [END] בסוף התגובה.

מבחן איכות לפני שליחה: אם אפשר להחליף את התגובה שלך בתגובה הקודמת שלך בלי שהשיחה תשתנה מהותית — התגובה חוזרת על עצמה. במקרה כזה כתוב תגובה אחרת שמקדמת את הסיטואציה.
'''

v21.scenario_prompt = human_scenario_prompt

if __name__ == '__main__':
    os.chdir(app.ROOT)
    print('Move A Mind v4.3 human dialogue progression')
    ThreadingHTTPServer(('0.0.0.0', app.PORT), v33.H).serve_forever()
