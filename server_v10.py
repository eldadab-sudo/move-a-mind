# Extend the prompt fix: in education the AI parent must open and remain the parent.
_previous_scenario_system = app.scenario_system
def scenario_system(sc, turn):
    base = _previous_scenario_system(sc, turn)
    if sc is app.SCENARIOS['teacher']:
        if turn == 0:
            return base + '''\nחובה: רוני ההורה פותח/ת עכשיו את השיחה בהתנגדות טבעית. המשתמש הוא המורה. כתוב רק את דברי ההורה, בגוף ראשון, 1-2 משפטים. אל תכתוב למשתמש מה עליו לומר.'''
        return base + '''\nזכור: המשתמש הוא המורה ואתה רוני, ההורה המתנגד/ת. המשך לענות רק כהורה.'''
    return base
app.scenario_system = scenario_system

